
import tkinter as tk
from tkinter import messagebox, filedialog

def Run_information(): #Gets and uses IPv4 info from main
    from main import get_ipv4, get_ipv6, get_ip_information

    status_label.config(text="Loading information...")
    Run_button.config(state="disabled")
    root.update_idletasks()

    ipv4 = get_ipv4()
    ipv6 = get_ipv6()

    ipv4_value.config(text=ipv4)
    ipv6_value.config(text=ipv6)

    if ipv4 != "Unavailable":
        information = get_ip_information(ipv4)

        if information:
            country_value.config(
                text=information.get("country_name") or "Unknown"
            )
            country_code_value.config(
                text=information.get("country") or "Unknown"
            )
            city_value.config(
                text=information.get("city") or "Unknown"
            )
            region_value.config(
                text=information.get("region") or "Unknown"
            )
            isp_value.config(
                text=information.get("org") or "Unknown"
            )
            asn_value.config(
                text=information.get("asn") or "Unknown"
            )

            status_label.config(
                text="Information fetched successfully."
            )

        else:
            clear_details()
            status_label.config(
                text="Could not fetch location information."
            )

    else:
        clear_details()
        status_label.config(
            text="Could not fetch public IP information."
        )

    Run_button.config(state="normal")

# Clears info field

def clear_details():
    country_value.config(text="-")
    country_code_value.config(text="-")
    city_value.config(text="-")
    region_value.config(text="-")
    isp_value.config(text="-")
    asn_value.config(text="-")


def clear_information():
    ipv4_value.config(text="-")
    ipv6_value.config(text="-")

    clear_details()

    status_label.config(text="Information cleared.")

# Automatic copy IP info

def copy_ip():
    ipv4 = ipv4_value.cget("text")

    if ipv4 in ("-", "Unavailable"):
        messagebox.showwarning(
            "Copy IP",
            "There is no available IPv4 address to copy."
        )
        return

    root.clipboard_clear()
    root.clipboard_append(ipv4)
    root.update()

    status_label.config(text="IPv4 address copied to clipboard.")

# Saves current information

def save_report():

    ipv4 = ipv4_value.cget("text")
    ipv6 = ipv6_value.cget("text")
    country = country_value.cget("text")
    country_code = country_code_value.cget("text")
    city = city_value.cget("text")
    region = region_value.cget("text")
    isp = isp_value.cget("text")
    asn = asn_value.cget("text")

    report = f"""
========================================
       IP ADDRESS INFORMATION
========================================

Public IPv4:    {ipv4}
Public IPv6:    {ipv6}

Country:        {country}
Country Code:   {country_code}
City:           {city}
Region:         {region}
ISP:            {isp}
ASN:            {asn}

========================================
Generated by IP Address Information App
========================================
"""

    file_path = filedialog.asksaveasfilename(
        defaultextension=".txt",
        filetypes=[
            ("Text Files", "*.txt"),
            ("All Files", "*.*")
        ],
        title="Save IP Report"
    )

    if file_path:
        try:
            with open(file_path, "w", encoding="utf-8") as file:
                file.write(report)

            status_label.config(
                text="Report saved successfully."
            )

        except OSError:
            messagebox.showerror(
                "Save Error",
                "The report could not be saved."
            )

# Labels

def create_information_row(parent, row, name):
    """Creates a label and value field for IP information."""

    label = tk.Label(
        parent,
        text=name,
        font=("Arial", 11, "bold"),
        width=15,
        anchor="w"
    )

    label.grid(row=row, column=0, padx=10, pady=6)

    value = tk.Label(
        parent,
        text="-",
        font=("Arial", 11),
        width=35,
        anchor="w"
    )

    value.grid(row=row, column=1, padx=10, pady=6)

    return value

# GUI

def create_application():
    global root
    global ipv4_value, ipv6_value
    global country_value, country_code_value
    global city_value, region_value
    global isp_value, asn_value
    global status_label, Run_button

    root = tk.Tk()

    root.title("IP Address Information")
    root.geometry("600x650")
    root.resizable(False, False)

    # Application title
    title_label = tk.Label(
        root,
        text="IP ADDRESS INFORMATION",
        font=("Arial", 20, "bold")
    )
    title_label.pack(pady=20)

    subtitle_label = tk.Label(
        root,
        text="Public IP and Network Information",
        font=("Arial", 10)
    )
    subtitle_label.pack()

    # Information fields
    info_frame = tk.Frame(root)
    info_frame.pack(pady=20)

    ipv4_value = create_information_row(
        info_frame, 0, "Public IPv4:"
    )
    ipv6_value = create_information_row(
        info_frame, 1, "Public IPv6:"
    )
    country_value = create_information_row(
        info_frame, 2, "Country:"
    )
    country_code_value = create_information_row(
        info_frame, 3, "Country Code:"
    )
    city_value = create_information_row(
        info_frame, 4, "City:"
    )
    region_value = create_information_row(
        info_frame, 5, "Region:"
    )
    isp_value = create_information_row(
        info_frame, 6, "ISP:"
    )
    asn_value = create_information_row(
        info_frame, 7, "ASN:"
    )

    # Application buttons
    button_frame = tk.Frame(root)
    button_frame.pack(pady=20)

    Run_button = tk.Button(
        button_frame,
        text="Run",
        width=12,
        command=Run_information
    )
    Run_button.grid(row=0, column=0, padx=5, pady=5)

    copy_button = tk.Button(
        button_frame,
        text="Copy IP",
        width=12,
        command=copy_ip
    )
    copy_button.grid(row=0, column=1, padx=5, pady=5)

    save_button = tk.Button(
        button_frame,
        text="Save Report",
        width=12,
        command=save_report
    )
    save_button.grid(row=1, column=0, padx=5, pady=5)

    clear_button = tk.Button(
        button_frame,
        text="Clear",
        width=12,
        command=clear_information
    )
    clear_button.grid(row=1, column=1, padx=5, pady=5)

    # Status message
    status_label = tk.Label(
        root,
        text="Ready",
        font=("Arial", 9)
    )
    status_label.pack(pady=10)

    root.mainloop()
